import ExcelJS from "exceljs";

/**
 * Departmental audit export, XLSX.
 *
 * One row per patient with the outcome fields an audit actually needs, plus a provenance
 * column on every measurement so an analyst cannot silently pool self-measured and
 * clinic-measured values.
 */

export interface AuditRow {
  mrn: string;
  ageAtSurgery: number | null;
  sex: string;
  operatedSide: string;
  dominance: string;
  procedure: string;
  dateOfSurgery: Date | null;
  operatingSurgeon: string;
  protocol: string | null;
  currentPhase: string | null;
  postOpDay: number | null;
  latestTam: number | null;
  latestTamMethod: string | null;
  latestTamDay: number | null;
  baselineQuickDash: number | null;
  latestQuickDash: number | null;
  baselinePrwhe: number | null;
  latestPrwhe: number | null;
  sessionsDue: number;
  sessionsCompleted: number;
  urgentAlerts: number;
  reviewAlerts: number;
  outreachAlerts: number;
}

const COLUMNS: { header: string; key: keyof AuditRow; width: number }[] = [
  { header: "MRN", key: "mrn", width: 14 },
  { header: "Age at surgery", key: "ageAtSurgery", width: 14 },
  { header: "Sex", key: "sex", width: 8 },
  { header: "Operated side", key: "operatedSide", width: 14 },
  { header: "Dominance", key: "dominance", width: 12 },
  { header: "Procedure", key: "procedure", width: 42 },
  { header: "Date of surgery", key: "dateOfSurgery", width: 16 },
  { header: "Operating surgeon", key: "operatingSurgeon", width: 22 },
  { header: "Protocol", key: "protocol", width: 34 },
  { header: "Current phase", key: "currentPhase", width: 26 },
  { header: "Post-op day", key: "postOpDay", width: 12 },
  { header: "Latest TAM", key: "latestTam", width: 12 },
  { header: "TAM measured by", key: "latestTamMethod", width: 17 },
  { header: "TAM post-op day", key: "latestTamDay", width: 16 },
  { header: "QuickDASH baseline", key: "baselineQuickDash", width: 18 },
  { header: "QuickDASH latest", key: "latestQuickDash", width: 17 },
  { header: "PRWHE baseline", key: "baselinePrwhe", width: 16 },
  { header: "PRWHE latest", key: "latestPrwhe", width: 14 },
  { header: "Sessions due", key: "sessionsDue", width: 13 },
  { header: "Sessions completed", key: "sessionsCompleted", width: 18 },
  { header: "Urgent alerts", key: "urgentAlerts", width: 13 },
  { header: "Review alerts", key: "reviewAlerts", width: 13 },
  { header: "Outreach alerts", key: "outreachAlerts", width: 15 },
];

export async function renderAuditWorkbook(
  rows: AuditRow[],
  meta: { department: string; hospital: string; generatedBy: string; generatedAt: Date },
): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = meta.hospital;
  workbook.created = meta.generatedAt;

  const notes = workbook.addWorksheet("Notes");
  notes.columns = [{ width: 110 }];
  notes.addRows([
    [`${meta.department}, ${meta.hospital}`],
    [`Generated by ${meta.generatedBy} on ${meta.generatedAt.toISOString().slice(0, 10)}`],
    [""],
    ["Provenance"],
    [
      "The TAM measured by column records whether a range of motion value was self-measured by the patient at home with a paper goniometer, or measured in clinic by a therapist.",
    ],
    [
      "These are not equivalent measurements. Do not pool them in an analysis without stratifying by this column.",
    ],
    [""],
    ["Scoring"],
    [
      "QuickDASH is scored 0 to 100 where higher is worse. PRWHE is scored 0 to 100 where higher is worse.",
    ],
    ["Total active motion is in degrees, per digit, using the summed flexion less extension deficit definition."],
    [""],
    ["Alert thresholds"],
    [
      "Plateau and non-adherence alert counts depend on departmental thresholds. Where those thresholds have not been signed off by a clinician, the corresponding rules did not run and the counts will be zero.",
    ],
  ]);
  notes.getRow(1).font = { bold: true, size: 12 };
  notes.getRow(4).font = { bold: true };
  notes.getRow(8).font = { bold: true };
  notes.getRow(12).font = { bold: true };

  const sheet = workbook.addWorksheet("Patients", {
    views: [{ state: "frozen", ySplit: 1 }],
  });
  sheet.columns = COLUMNS.map((column) => ({
    header: column.header,
    key: column.key,
    width: column.width,
  }));

  sheet.getRow(1).font = { bold: true };
  sheet.getRow(1).fill = {
    type: "pattern",
    pattern: "solid",
    fgColor: { argb: "FFEFF1F5" },
  };

  for (const row of rows) {
    sheet.addRow(row);
  }

  sheet.autoFilter = {
    from: { row: 1, column: 1 },
    to: { row: 1, column: COLUMNS.length },
  };

  sheet.getColumn("dateOfSurgery").numFmt = "yyyy-mm-dd";

  const buffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(buffer);
}
